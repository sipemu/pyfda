def main() -> None:
    """Entry point: generate or drift-check all snippet fragments."""
    check = "--check" in sys.argv
    _SNIPPETS_DIR.mkdir(parents=True, exist_ok=True)
    stale: list[str] = []

    for name, source in SNIPPETS:
        out = _run(source, extra_ns=_EXTRA_NS)
        content = _render(source, out)
        target = _SNIPPETS_DIR / f"{name}.tex"

        if check:
            if not target.exists() or target.read_text(encoding="utf-8") != content:
                stale.append(str(target))
        else:
            target.write_text(content, encoding="utf-8")

    if check:
        if stale:
            print(
                "DRIFT: stale/missing snippets -- re-run gen_snippets.py and commit:",
                file=sys.stderr,
            )
            for s in stale:
                print(f"  {s}", file=sys.stderr)
            sys.exit(1)
        print("gen_snippets: OK (no drift)")
    else:
        print(f"Wrote {len(SNIPPETS)} snippet fragment(s) to {_SNIPPETS_DIR}")


if __name__ == "__main__":
    main()
